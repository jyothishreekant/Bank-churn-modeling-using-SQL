select * from `churn modeling`;

-- CONTRY WISE CUSTOMER COUNT
SELECT COUNTRY,COUNT(*) AS TOTAL_CUSTOMER
FROM  `CHURN MODELING`
GROUP BY COUNTRY;

-- COUNTRY WISE CHURN COUNT
SELECT COUNTRY,COUNT(*) AS CHURNED_CUSTOMER
FROM `CHURN MODELING`
WHERE EXITED =1
GROUP BY COUNTRY;

-- ACTIVE VS INACTIVE CUSTOMER
SELECT IsActiveMember,COUNT(*) AS TOTAL
FROM  `CHURN MODELING`
GROUP BY IsActiveMember;

-- PRODUCT WISE CHURN ANALYSIS
SELECT NUMOFPRODUCTS,COUNT(*) AS CHURNED_CUSTOMER
FROM `CHURN MODELING`
WHERE EXITED =1
GROUP BY NUMOFPRODUCTS;

-- AGE GROUP ANALYSIS
SELECT CASE 
            WHEN AGE<30 THEN 'BELOW 30'
			WHEN AGE BETWEEN 30 AND 40 THEN '30-40'
            WHEN AGE BETWEEN 41 AND 50 THEN '41-50'
            ELSE 'ABOVE 50'
            END AS AGE_GROUP,
            COUNT(*) AS TOTAL_CUSTOMERS
            FROM `CHURN MODELING`
            GROUP BY AGE_GROUP;

-- AVG CUSTOMER BALANCE
SELECT ROUND(AVG(BALANCE),2) AS AVG_BALANCE
FROM `CHURN MODELING`;

-- TOTA BANK BALANCE
SELECT ROUND(SUM(BALANCE)/1000000,2) AS TOTAL_BALANCE_MILLION
FROM `CHURN MODELING`;

-- CUSTOMER WITH ZERO BALANCE
SELECT CUSTOMERID,SURNAME,COUNTRY,BALANCE
FROM `CHURN MODELING`
WHERE BALANCE=0;

-- COUNTRY WISE AVG BALANCE
SELECT COUNTRY,
AVG(ESTIMATEDSALARY) AS AVG_SALARY
FROM `CHURN MODELING`
GROUP BY COUNTRY;

-- CUSTOMER CHURN PERCENTAGE
SELECT ROUND(SUM(EXITED)* 100.0 / COUNT(*),2)
 AS CHURN_PERCNTAGE 
FROM `CHURN MODELING`;




